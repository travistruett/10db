import {
  DomainError,
  EventsHead,
  HealthResponse,
  InboxAnswer,
  InboxItemId,
  InboxState,
  KeepAwakeInput,
  ProjectId,
  ProjectInput,
  PROTOCOL_VERSION,
  SystemCheckDto,
  TaskId,
  TaskInput,
  WorkstreamId,
} from '@10db/contracts';
import { Hono } from 'hono';
import { cors } from 'hono/cors';
import type { UpgradeWebSocket } from 'hono/ws';
import { z } from 'zod';
import type { ApiServices } from './services';
import { streamEvents } from './stream';

export interface ApiDeps {
  readonly startedAt: Date;
  /** Origins the UI is served from (Vite dev server, Tauri webview). */
  readonly allowedOrigins: readonly string[];
  /** The UI's bearer token, generated by the daemon at start. */
  readonly token: string;
  readonly services: ApiServices;
  readonly upgradeWebSocket: UpgradeWebSocket;
  /** The MCP endpoint; it authenticates sessions itself. */
  mcp(req: Request): Promise<Response>;
  /** Called with every error the API answers as a 500, so the daemon can log it. */
  onUnexpectedError(error: unknown): void;
}

const STATUS = { not_found: 404, conflict: 409, invalid: 400 } as const;
const OPEN_PATHS = new Set(['/health', '/mcp']);
const STREAM_PATH = '/events/stream';

function sameToken(a: string, b: string): boolean {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i += 1) diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return diff === 0;
}

const Cursor = z.coerce.number().int().min(0).catch(0);
const Limit = z.coerce.number().int().min(1).max(1000).catch(500);
const StateList = z
  .string()
  .optional()
  // InboxState is an `as const` object, not a schema, so wrap it in z.enum to parse.
  .transform((s) => (s ? s.split(',').map((x) => z.enum(InboxState).parse(x)) : null));

export function createApp(deps: ApiDeps) {
  const app = new Hono()
    .use(
      '*',
      cors({
        origin: (origin) => (deps.allowedOrigins.includes(origin) ? origin : null),
        allowHeaders: ['Authorization', 'Content-Type'],
      }),
    )
    .use('*', async (c, next) => {
      if (OPEN_PATHS.has(c.req.path)) return next();
      const presented =
        c.req.path === STREAM_PATH
          ? (c.req.query('token') ?? '')
          : (/^Bearer (.+)$/.exec(c.req.header('authorization') ?? '')?.[1] ?? '');
      if (!sameToken(presented, deps.token)) return c.json({ error: 'unauthorized' }, 401);
      return next();
    })
    .all('/mcp', (c) => deps.mcp(c.req.raw))
    .get('/health', (c) =>
      c.json(
        HealthResponse.parse({
          status: 'ok',
          protocolVersion: PROTOCOL_VERSION,
          startedAt: deps.startedAt.toISOString(),
        }),
      ),
    )
    .get('/projects', (c) => c.json(deps.services.listProjects()))
    .post('/projects', async (c) =>
      c.json(deps.services.createProject(ProjectInput.parse(await c.req.json())), 201),
    )
    .get('/projects/:projectId/tasks', (c) =>
      c.json(deps.services.listTasks(ProjectId.parse(c.req.param('projectId')))),
    )
    .post('/projects/:projectId/tasks', async (c) =>
      c.json(
        deps.services.createTask(
          ProjectId.parse(c.req.param('projectId')),
          TaskInput.parse(await c.req.json()),
        ),
        201,
      ),
    )
    .post('/projects/:projectId/mcp-servers/review', (c) =>
      c.json(deps.services.reviewProjectMcp(ProjectId.parse(c.req.param('projectId')))),
    )
    .post('/tasks/:taskId/start', (c) =>
      c.json(deps.services.startTask(TaskId.parse(c.req.param('taskId'))), 201),
    )
    .get('/workstreams', (c) =>
      c.json(deps.services.listWorkstreams({ active: c.req.query('active') !== 'false' })),
    )
    .post('/workstreams/:id/cancel', async (c) =>
      c.json(await deps.services.cancelWorkstream(WorkstreamId.parse(c.req.param('id')))),
    )
    .post('/workstreams/:id/retry', (c) =>
      c.json(deps.services.retryWorkstream(WorkstreamId.parse(c.req.param('id')))),
    )
    .get('/inbox', (c) =>
      c.json(deps.services.listInbox({ states: StateList.parse(c.req.query('state')) })),
    )
    .post('/inbox/:id/answer', async (c) =>
      c.json(
        deps.services.answerInbox(
          InboxItemId.parse(c.req.param('id')),
          InboxAnswer.parse(await c.req.json()),
        ),
      ),
    )
    .get('/events', (c) =>
      c.json(
        deps.services.eventsAfter(
          Cursor.parse(c.req.query('after')),
          Limit.parse(c.req.query('limit')),
        ),
      ),
    )
    .get('/events/head', (c) => c.json(EventsHead.parse({ seq: deps.services.eventsHead() })))
    .get('/system', async (c) => c.json(SystemCheckDto.parse(await deps.services.systemCheck())))
    .get('/settings/keep-awake', (c) => c.json(deps.services.keepAwake()))
    .put('/settings/keep-awake', async (c) =>
      c.json(deps.services.setKeepAwake(KeepAwakeInput.parse(await c.req.json()).mode)),
    )
    .get(
      STREAM_PATH,
      deps.upgradeWebSocket((c) => {
        const after = Cursor.parse(c.req.query('after'));
        let stop: (() => void) | null = null;
        return {
          onOpen(_event, ws) {
            stop = streamEvents(after, deps.services, (event) => {
              ws.send(JSON.stringify(event));
            });
          },
          onClose() {
            stop?.();
          },
        };
      }),
    );

  app.onError((error, c) => {
    if (error instanceof z.ZodError) {
      return c.json(
        {
          error: 'invalid',
          issues: error.issues.map((i) => ({ path: i.path.join('.'), message: i.message })),
        },
        400,
      );
    }
    if (error instanceof DomainError) {
      return c.json({ error: error.code, message: error.message }, STATUS[error.code]);
    }
    // `c.req.json()` throws a SyntaxError for a body that is not JSON.
    if (error instanceof SyntaxError)
      return c.json({ error: 'invalid', message: 'The body is not valid JSON' }, 400);
    deps.onUnexpectedError(error);
    return c.json({ error: 'internal' }, 500);
  });
  return app;
}

export type AppType = ReturnType<typeof createApp>;
