import {
  BatchId,
  BatchStartInput,
  BoardColumnDelete,
  BoardColumnId,
  BoardColumnInput,
  BoardColumnPatch,
  DomainError,
  EventsHead,
  FlowId,
  FlowInput,
  FlowPatch,
  HealthResponse,
  InboxAnswer,
  InboxItemId,
  InboxState,
  KeepAwakeInput,
  ModelProfileId,
  ModelProfilePatch,
  PersonaId,
  PersonaInput,
  PersonaPatch,
  PersonInput,
  ProjectId,
  ProjectInput,
  ProjectPatch,
  PROTOCOL_VERSION,
  RoutingRulesInput,
  SystemCheckDto,
  TaskId,
  TaskInput,
  TaskMove,
  TaskPatch,
  TeamInput,
  WorkstreamId,
} from '@10db/contracts';
import { Hono } from 'hono';
import { cors } from 'hono/cors';
import { HTTPException } from 'hono/http-exception';
import { validator } from 'hono/validator';
import type { UpgradeWebSocket } from 'hono/ws';
import { z } from 'zod';
import type { ApiServices } from './services';
import { streamEvents } from './stream';

export interface ApiDeps {
  readonly startedAt: Date;
  /** Origins the UI is served from (Vite dev server, Tauri webview). */
  readonly allowedOrigins: readonly string[];
  /** The UI's bearer token, generated by the daemon at start. */
  readonly token: string;
  readonly services: ApiServices;
  readonly upgradeWebSocket: UpgradeWebSocket;
  /** The MCP endpoint; it authenticates sessions itself. */
  mcp(req: Request): Promise<Response>;
  /** Called with every error the API answers as a 500, so the daemon can log it. */
  onUnexpectedError(error: unknown): void;
}

const STATUS = { not_found: 404, conflict: 409, invalid: 400 } as const;
const OPEN_PATHS = new Set(['/health', '/mcp']);
const STREAM_PATH = '/events/stream';

function sameToken(a: string, b: string): boolean {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i += 1) diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return diff === 0;
}

const Cursor = z.coerce.number().int().min(0).catch(0);
const Limit = z.coerce.number().int().min(1).max(1000).catch(500);
const StateList = z
  .string()
  .optional()
  // InboxState is an `as const` object, not a schema, so wrap it in z.enum to parse.
  .transform((s) => (s ? s.split(',').map((x) => z.enum(InboxState).parse(x)) : null));

export function createApp(deps: ApiDeps) {
  const app = new Hono()
    .use(
      '*',
      cors({
        origin: (origin) => (deps.allowedOrigins.includes(origin) ? origin : null),
        allowHeaders: ['Authorization', 'Content-Type'],
      }),
    )
    .use('*', async (c, next) => {
      if (OPEN_PATHS.has(c.req.path)) return next();
      const presented =
        c.req.path === STREAM_PATH
          ? (c.req.query('token') ?? '')
          : (/^Bearer (.+)$/.exec(c.req.header('authorization') ?? '')?.[1] ?? '');
      if (!sameToken(presented, deps.token)) return c.json({ error: 'unauthorized' }, 401);
      return next();
    })
    .use(STREAM_PATH, async (c, next) => {
      // Browsers don't apply CORS to WebSockets; a page on another origin must not read the stream.
      // Non-browser clients send no Origin and are covered by the token alone.
      const origin = c.req.header('origin');
      if (origin !== undefined && !deps.allowedOrigins.includes(origin))
        return c.json({ error: 'forbidden origin' }, 403);
      return next();
    })
    .all('/mcp', (c) => deps.mcp(c.req.raw))
    .get('/health', (c) =>
      c.json(
        HealthResponse.parse({
          status: 'ok',
          protocolVersion: PROTOCOL_VERSION,
          startedAt: deps.startedAt.toISOString(),
        }),
      ),
    )
    .get('/projects', (c) => c.json(deps.services.listProjects()))
    .post(
      '/projects',
      validator('json', (value): ProjectInput => ProjectInput.parse(value)),
      (c) => c.json(deps.services.createProject(c.req.valid('json')), 201),
    )
    .get('/projects/:projectId/tasks', (c) =>
      c.json(deps.services.listTasks(ProjectId.parse(c.req.param('projectId')))),
    )
    .post(
      '/projects/:projectId/tasks',
      validator('json', (value): TaskInput => TaskInput.parse(value)),
      (c) =>
        c.json(
          deps.services.createTask(ProjectId.parse(c.req.param('projectId')), c.req.valid('json')),
          201,
        ),
    )
    .post('/projects/:projectId/mcp-servers/review', (c) =>
      c.json(deps.services.reviewProjectMcp(ProjectId.parse(c.req.param('projectId')))),
    )
    .post(
      '/projects/:projectId/batches',
      validator('json', (value): BatchStartInput => BatchStartInput.parse(value)),
      (c) =>
        c.json(
          deps.services.startBatch(ProjectId.parse(c.req.param('projectId')), c.req.valid('json')),
          202,
        ),
    )
    .post('/batches/:batchId/ship', (c) =>
      c.json(deps.services.shipBatch(BatchId.parse(c.req.param('batchId')))),
    )
    .post('/batches/:batchId/abandon', (c) =>
      c.json(deps.services.abandonBatch(BatchId.parse(c.req.param('batchId')))),
    )
    .get('/flows', (c) => c.json(deps.services.listFlows()))
    .patch(
      '/projects/:projectId',
      validator('json', (value): ProjectPatch => ProjectPatch.parse(value)),
      (c) =>
        c.json(
          deps.services.patchProject(
            ProjectId.parse(c.req.param('projectId')),
            c.req.valid('json'),
          ),
        ),
    )
    .get('/projects/:projectId/team', (c) =>
      c.json(deps.services.getTeam(ProjectId.parse(c.req.param('projectId')))),
    )
    .put(
      '/projects/:projectId/team',
      validator('json', (value): TeamInput => TeamInput.parse(value)),
      (c) =>
        c.json(
          deps.services.setTeam(ProjectId.parse(c.req.param('projectId')), c.req.valid('json')),
        ),
    )
    .get('/projects/:projectId/routing-rules', (c) =>
      c.json(deps.services.listRoutingRules(ProjectId.parse(c.req.param('projectId')))),
    )
    .put(
      '/projects/:projectId/routing-rules',
      validator('json', (value): RoutingRulesInput => RoutingRulesInput.parse(value)),
      (c) =>
        c.json(
          deps.services.setRoutingRules(
            ProjectId.parse(c.req.param('projectId')),
            c.req.valid('json'),
          ),
        ),
    )
    .get('/personas', (c) => c.json(deps.services.listPersonas()))
    .post(
      '/personas',
      validator('json', (value): PersonaInput => PersonaInput.parse(value)),
      (c) => c.json(deps.services.createPersona(c.req.valid('json')), 201),
    )
    .patch(
      '/personas/:personaId',
      validator('json', (value): PersonaPatch => PersonaPatch.parse(value)),
      (c) =>
        c.json(
          deps.services.patchPersona(
            PersonaId.parse(c.req.param('personaId')),
            c.req.valid('json'),
          ),
        ),
    )
    .get('/people', (c) => c.json(deps.services.listPeople()))
    .post(
      '/people',
      validator('json', (value): PersonInput => PersonInput.parse(value)),
      (c) => c.json(deps.services.createPerson(c.req.valid('json')), 201),
    )
    .post(
      '/flows',
      validator('json', (value): FlowInput => FlowInput.parse(value)),
      (c) => c.json(deps.services.createFlow(c.req.valid('json')), 201),
    )
    .patch(
      '/flows/:flowId',
      validator('json', (value): FlowPatch => FlowPatch.parse(value)),
      (c) =>
        c.json(deps.services.patchFlow(FlowId.parse(c.req.param('flowId')), c.req.valid('json'))),
    )
    .get('/model-profiles', (c) => c.json(deps.services.listModelProfiles()))
    .patch(
      '/model-profiles/:profileId',
      validator('json', (value): ModelProfilePatch => ModelProfilePatch.parse(value)),
      (c) =>
        c.json(
          deps.services.patchModelProfile(
            ModelProfileId.parse(c.req.param('profileId')),
            c.req.valid('json'),
          ),
        ),
    )
    .get('/benchmarks/status', (c) => c.json(deps.services.benchmarkStatus()))
    .post('/benchmarks/sync', async (c) => c.json(await deps.services.syncBenchmarks()))
    .get('/benchmarks/models', (c) => c.json(deps.services.listAaModels()))
    .patch(
      '/tasks/:taskId',
      validator('json', (value): TaskPatch => TaskPatch.parse(value)),
      (c) =>
        c.json(deps.services.patchTask(TaskId.parse(c.req.param('taskId')), c.req.valid('json'))),
    )
    .post(
      '/tasks/:taskId/move',
      validator('json', (value): TaskMove => TaskMove.parse(value)),
      (c) =>
        c.json(deps.services.moveTask(TaskId.parse(c.req.param('taskId')), c.req.valid('json'))),
    )
    .get('/projects/:projectId/board-columns', (c) =>
      c.json(deps.services.listBoardColumns(ProjectId.parse(c.req.param('projectId')))),
    )
    .post(
      '/projects/:projectId/board-columns',
      validator('json', (value): BoardColumnInput => BoardColumnInput.parse(value)),
      (c) =>
        c.json(
          deps.services.createBoardColumn(
            ProjectId.parse(c.req.param('projectId')),
            c.req.valid('json'),
          ),
          201,
        ),
    )
    .patch(
      '/board-columns/:columnId',
      validator('json', (value): BoardColumnPatch => BoardColumnPatch.parse(value)),
      (c) =>
        c.json(
          deps.services.patchBoardColumn(
            BoardColumnId.parse(c.req.param('columnId')),
            c.req.valid('json'),
          ),
        ),
    )
    .post(
      '/board-columns/:columnId/delete',
      validator('json', (value): BoardColumnDelete => BoardColumnDelete.parse(value)),
      (c) =>
        c.json(
          deps.services.deleteBoardColumn(
            BoardColumnId.parse(c.req.param('columnId')),
            c.req.valid('json'),
          ),
        ),
    )
    .get('/tasks/:taskId/step-plan', (c) =>
      c.json(deps.services.stepPlan(TaskId.parse(c.req.param('taskId')))),
    )
    .post('/tasks/:taskId/start', (c) => {
      const started = deps.services.startTask(TaskId.parse(c.req.param('taskId')));
      // A pull-request start answers before its branch is cut: 202, as a batch start does.
      switch (started.kind) {
        case 'workstream':
          return c.json(started.workstream, 201);
        case 'batch':
          return c.json(started.batch, 202);
      }
    })
    .get(
      '/workstreams',
      validator('query', (query): { active?: string } =>
        typeof query['active'] === 'string' ? { active: query['active'] } : {},
      ),
      (c) =>
        c.json(deps.services.listWorkstreams({ active: c.req.valid('query').active !== 'false' })),
    )
    .post('/workstreams/:id/cancel', async (c) =>
      c.json(await deps.services.cancelWorkstream(WorkstreamId.parse(c.req.param('id')))),
    )
    .post('/workstreams/:id/retry', (c) =>
      c.json(deps.services.retryWorkstream(WorkstreamId.parse(c.req.param('id')))),
    )
    .get(
      '/inbox',
      validator('query', (query): { state?: string } =>
        typeof query['state'] === 'string' ? { state: query['state'] } : {},
      ),
      (c) =>
        c.json(deps.services.listInbox({ states: StateList.parse(c.req.valid('query').state) })),
    )
    .post(
      '/inbox/:id/answer',
      validator('json', (value): InboxAnswer => InboxAnswer.parse(value)),
      (c) =>
        c.json(
          deps.services.answerInbox(InboxItemId.parse(c.req.param('id')), c.req.valid('json')),
        ),
    )
    .get('/events', (c) =>
      c.json(
        deps.services.eventsAfter(
          Cursor.parse(c.req.query('after')),
          Limit.parse(c.req.query('limit')),
        ),
      ),
    )
    .get('/events/head', (c) => c.json(EventsHead.parse({ seq: deps.services.eventsHead() })))
    .get('/system', async (c) => c.json(SystemCheckDto.parse(await deps.services.systemCheck())))
    .get('/settings/keep-awake', (c) => c.json(deps.services.keepAwake()))
    .put(
      '/settings/keep-awake',
      validator('json', (value): z.infer<typeof KeepAwakeInput> => KeepAwakeInput.parse(value)),
      (c) => c.json(deps.services.setKeepAwake(c.req.valid('json').mode)),
    )
    .get(
      STREAM_PATH,
      deps.upgradeWebSocket((c) => {
        const after = Cursor.parse(c.req.query('after'));
        let stop: (() => void) | null = null;
        return {
          onOpen(_event, ws) {
            stop = streamEvents(after, deps.services, (event) => {
              ws.send(JSON.stringify(event));
            });
          },
          onClose() {
            stop?.();
          },
        };
      }),
    );

  app.onError((error, c) => {
    // Hono's own request errors (a malformed body, a missing content type) carry their status;
    // answer them in the API's JSON error shape.
    if (error instanceof HTTPException)
      return c.json({ error: 'invalid', message: error.message }, error.status);
    if (error instanceof z.ZodError) {
      return c.json(
        {
          error: 'invalid',
          issues: error.issues.map((i) => ({ path: i.path.join('.'), message: i.message })),
        },
        400,
      );
    }
    if (error instanceof DomainError) {
      return c.json({ error: error.code, message: error.message }, STATUS[error.code]);
    }
    // `c.req.json()` throws a SyntaxError for a body that is not JSON.
    if (error instanceof SyntaxError)
      return c.json({ error: 'invalid', message: 'The body is not valid JSON' }, 400);
    deps.onUnexpectedError(error);
    return c.json({ error: 'internal' }, 500);
  });
  return app;
}

export type AppType = ReturnType<typeof createApp>;
